// Bundles the webview client into a TypeScript string constant so dashboardHtml.ts stays
// pure and host-free. Replaces the previous Function.prototype.toString() delivery, which
// could not capture imports and therefore forced the whole client into one closure.
import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const target = join(root, 'src', 'generated', 'dashboardClientBundle.ts');

const result = await build({
  entryPoints: [join(root, 'src', 'dashboardClientEntry.ts')],
  bundle: true,
  format: 'iife',
  target: 'es2022',
  platform: 'browser',
  minify: false,
  write: false,
  legalComments: 'none',
});

const [output] = result.outputFiles;
const code = output.text.trimEnd();

// The bundle is inlined between <script> tags; these sequences could end or re-mode the element.
if (/<\/script|<!--|<script/i.test(code)) {
  throw new Error('Bundled dashboard client contains a literal </script, <!-- or <script sequence');
}

const contents = [
  '// GENERATED by scripts/buildClient.mjs. Do not edit; run `npm run build:client`.',
  '',
  `export const DASHBOARD_CLIENT_BUNDLE = ${JSON.stringify(code)};`,
  '',
].join('\n');

mkdirSync(dirname(target), { recursive: true });
let existing;
try {
  existing = readFileSync(target, 'utf8');
} catch {
  existing = undefined;
}
// Avoid rewriting an unchanged file so incremental TypeScript builds stay warm.
if (existing !== contents) {
  writeFileSync(target, contents);
}
console.log(`dashboard client bundle: ${(code.length / 1024).toFixed(1)} KB`);
